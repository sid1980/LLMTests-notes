def seq(nums):
    return " ".join(str(v) for v in nums)


def grid(rows):
    return "\n".join(" ".join(str(v) for v in r) for r in rows)


def _make_10x10(minval, minr, minc):
    a = [[i * 10 + j + 1 for j in range(10)] for i in range(10)]
    a[minr][minc] = minval
    return grid(a)


def _make_7x7(fn):
    return grid([[fn(i, j) for j in range(7)] for i in range(7)])


def _make_6x8(fn):
    return grid([[fn(i, j) for j in range(8)] for i in range(6)])


