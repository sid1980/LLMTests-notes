def compile_and_run(src: Path, extra_flags, stdin: str) -> str:
    """Скомпилировать и прогнать, вернуть stdout (UTF-8)."""
    flags = BASE_FLAGS + list(extra_flags)
    with tempfile_tmp() as tmpdir:
        td = Path(tmpdir)
        exe = td / ("sol.exe" if os.name == "nt" else "sol")
        cmd = [CC, *flags, "-o", str(exe), str(src)]
        cp = subprocess.run(cmd, capture_output=True, text=True,
                            encoding="utf-8", errors="replace")
        if cp.returncode != 0:
            raise RuntimeError(f"compile failed {src.name}: {cp.stderr}")
        run = subprocess.run([str(exe)], input=stdin, capture_output=True,
                             text=True, encoding="utf-8", errors="replace")
        return run.stdout


def tempfile_tmp():
    import tempfile
    return tempfile.TemporaryDirectory(prefix="cbench_build_")


def build():
    # Сохранить задачи, которые НЕ пересобираются этим скриптом (например c-matrix-001).
    preserved = []
    if CASES_JSON.exists():
        try:
            existing = json.loads(CASES_JSON.read_text(encoding="utf-8"))
        except Exception:
            existing = []
        regen_ids = {s[0] for s in SPECS}
        preserved = [c for c in existing if c.get("id") not in regen_ids]

    cases = []
    for (cid, topic, level, flags, url, title, body, tests) in SPECS:
        src = SOL_DIR / f"{cid}.c"
        if not src.exists():
            raise RuntimeError(f"нет решения {src}")
        test_specs = []
        for stdin in tests:
            stdout = compile_and_run(src, flags, stdin)
            test_specs.append({
                "argv": [],
                "stdin": stdin,
                "files": [],
                "expected": {"stdout": stdout, "files": [], "exit_code": 0},
                "timeout_s": 20,
            })
        cases.append({
            "id": cid,
            "topic": topic,
            "level": level,
            "kind": "program",
            "io_mode": "stdin_stdout",
            "compile_flags": list(flags),
            "prompt": HDR + body,
            "tests": test_specs,
        })
        # заметка
        NOTES_DIR.mkdir(parents=True, exist_ok=True)
        note = NOTES_DIR / f"{cid}.md"
        note.write_text(f"{url}\n{title}\n\n{body}\n", encoding="utf-8")

    # Сортировка: easy -> medium -> hard, затем по id (уже примерно так).
    order = {"easy": 0, "medium": 1, "hard": 2}
    cases.sort(key=lambda c: (order[c["level"]], c["id"]))
    cases = preserved + cases

    CASES_JSON.write_text(json.dumps(cases, ensure_ascii=False, indent=2) + "\n",
                          encoding="utf-8")
    by_level = {}
    for c in cases:
        by_level[c["level"]] = by_level.get(c["level"], 0) + 1
    print(f"OK: {len(cases)} cases -> {CASES_JSON}")
    print("by level:", by_level)


if __name__ == "__main__":
    build()
